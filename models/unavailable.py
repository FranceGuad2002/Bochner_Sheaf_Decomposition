"""Models used in the paper whose implementation is not distributed in this release.

The joint sheaf diffusion models (JointSheafParams, JointSheafParamsAlt and the
JointSheafVanilla initialiser) are the method of Hernandez Caralt et al., "Joint
Diffusion Processes as an Inductive Bias in Sheaf Neural Networks" (GRaM workshop,
2024). Their code is not ours to redistribute, so it is not included here. Asking for
one of these models raises a clear error instead of failing somewhere downstream.

The outputs of the Joint runs reported in the paper are part of the accompanying
Zenodo record (see the README), so every table and figure built from them can still
be regenerated by the analysis scripts.
"""

JOINT_SHEAF_MODELS = ('JointSheafParams', 'JointSheafParamsAlt', 'JointSheafVanilla')

_MESSAGE = (
    "{name} is not included in this release. It is the joint sheaf diffusion model of "
    "Hernandez Caralt et al. (2024), whose implementation is available from the authors "
    "of that work. The outputs of the {name} runs used in the paper are in the Zenodo "
    "record listed in the README, and the analysis scripts can rebuild the paper's "
    "tables from them."
)


class JointModelUnavailable(NotImplementedError):
    """Raised whenever a joint sheaf diffusion model is requested."""

    def __init__(self, name):
        super().__init__(_MESSAGE.format(name=name))


def unavailable_model(name):
    """Return a stand-in class for model `name` that raises JointModelUnavailable on construction."""

    class _Unavailable:
        def __init__(self, *args, **kwargs):
            raise JointModelUnavailable(name)

    _Unavailable.__name__ = _Unavailable.__qualname__ = f'{name}Unavailable'
    return _Unavailable
